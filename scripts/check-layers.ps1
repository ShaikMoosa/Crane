param([switch]$SelfTest)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

function Get-CargoMetadata {
    param([Parameter(Mandatory = $true)][string]$ManifestPath)
    $json = & cargo metadata --format-version 1 --no-deps --locked --manifest-path $ManifestPath 2>&1
    if ($LASTEXITCODE -ne 0) {
        throw "cargo metadata failed:`n$($json -join "`n")"
    }
    ($json -join "`n") | ConvertFrom-Json
}

function Test-CraneLayers {
    param([Parameter(Mandatory = $true)][string]$ManifestPath)

    $metadata = Get-CargoMetadata -ManifestPath $ManifestPath
    $workspaceIds = @{}
    foreach ($id in $metadata.workspace_members) { $workspaceIds[$id] = $true }
    $forbiddenRuntime = @('tauri', 'tauri-runtime', 'tauri-runtime-wry', 'wry', 'webview2-com')
    $allowedCrane = @{
        'crane-domain' = @()
        'crane-application' = @('crane-domain')
        'crane-platform' = @('crane-application', 'crane-domain')
        'crane-storage' = @('crane-application', 'crane-domain', 'crane-platform')
        'crane-desktop' = @('crane-application', 'crane-domain', 'crane-platform', 'crane-storage')
    }
    $violations = [System.Collections.Generic.List[string]]::new()

    foreach ($package in $metadata.packages) {
        if (-not $workspaceIds.ContainsKey($package.id)) { continue }
        foreach ($dependency in $package.dependencies) {
            if ($forbiddenRuntime -contains $dependency.name) {
                $display = if ($dependency.rename) { "$($dependency.rename) (package $($dependency.name))" } else { $dependency.name }
                $violations.Add("$($package.name) depends on forbidden runtime $display")
            }
            if ($dependency.name.StartsWith('crane-') -and $allowedCrane.ContainsKey($package.name)) {
                if ($allowedCrane[$package.name] -notcontains $dependency.name) {
                    $violations.Add("$($package.name) illegally depends on $($dependency.name)")
                }
            }
        }
    }
    if ($violations.Count -gt 0) {
        throw ($violations -join "`n")
    }
    Write-Host 'Crane dependency layers are valid.'
}

function Assert-Fails {
    param([scriptblock]$Action, [string]$ExpectedText)
    try {
        & $Action | Out-Null
    }
    catch {
        if ($_.Exception.Message -notmatch [regex]::Escape($ExpectedText)) {
            throw "Expected '$ExpectedText' but got: $($_.Exception.Message)"
        }
        return
    }
    throw "Self-test expected failure containing '$ExpectedText'."
}

if ($SelfTest) {
    $testRoot = Join-Path ([System.IO.Path]::GetTempPath()) ("crane-layers-selftest-" + [guid]::NewGuid())
    New-Item -ItemType Directory -Path (Join-Path $testRoot 'domain/src') -Force | Out-Null
    New-Item -ItemType Directory -Path (Join-Path $testRoot 'tauri-stub/src') -Force | Out-Null
    try {
        Set-Content -LiteralPath (Join-Path $testRoot 'Cargo.lock') -Value "# This file is automatically @generated by Cargo.`nversion = 4" -NoNewline
        Set-Content -LiteralPath (Join-Path $testRoot 'tauri-stub/Cargo.toml') -Value "[package]`nname = `"tauri`"`nversion = `"0.0.0`"`nedition = `"2021`"" -NoNewline
        Set-Content -LiteralPath (Join-Path $testRoot 'tauri-stub/src/lib.rs') -Value '' -NoNewline
        Set-Content -LiteralPath (Join-Path $testRoot 'domain/src/lib.rs') -Value '' -NoNewline
        $manifest = Join-Path $testRoot 'Cargo.toml'
        Set-Content -LiteralPath $manifest -Value "[workspace]`nmembers = [`"domain`", `"tauri-stub`"]`nresolver = `"2`"" -NoNewline
        Set-Content -LiteralPath (Join-Path $testRoot 'domain/Cargo.toml') -Value "[package]`nname = `"crane-domain`"`nversion = `"0.0.0`"`nedition = `"2021`"" -NoNewline
        & cargo generate-lockfile --manifest-path $manifest 2>&1 | Out-Null
        if ($LASTEXITCODE -ne 0) { throw 'Could not generate the legal fixture lockfile.' }
        Test-CraneLayers -ManifestPath $manifest | Out-Null

        Add-Content -LiteralPath (Join-Path $testRoot 'domain/Cargo.toml') -Value "`n[dependencies]`ntauri-alias = { package = `"tauri`", path = `"../tauri-stub`" }"
        & cargo generate-lockfile --manifest-path $manifest 2>&1 | Out-Null
        if ($LASTEXITCODE -ne 0) { throw 'Could not generate the illegal fixture lockfile.' }
        Assert-Fails { Test-CraneLayers -ManifestPath $manifest } 'tauri-alias (package tauri)'
        Write-Host 'check-layers self-test passed'
    }
    finally {
        Remove-Item -LiteralPath $testRoot -Recurse -Force
    }
    exit 0
}

Test-CraneLayers -ManifestPath (Join-Path $PSScriptRoot '..\Cargo.toml')
